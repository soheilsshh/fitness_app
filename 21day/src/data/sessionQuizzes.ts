export function getSessionQuiz(videoId: number): QuizQuestion[] | null {
  const quiz = SESSION_QUIZZES[videoId];
  if (!quiz || quiz.length !== 3) return null;

  // Deterministic shuffle so the correct choice isn't always option "الف"
  return quiz.map((q, qi) => {
    const seed = videoId * 17 + qi * 31;
    const order = [0, 1, 2] as const;
    const rotated = [order[seed % 3], order[(seed + 1) % 3], order[(seed + 2) % 3]] as [
      0 | 1 | 2,
      0 | 1 | 2,
      0 | 1 | 2,
    ];
    const options = [q.options[rotated[0]], q.options[rotated[1]], q.options[rotated[2]]] as [
      string,
      string,
      string,
    ];
    const correctIndex = rotated.indexOf(q.correctIndex) as 0 | 1 | 2;
    return { ...q, options, correctIndex };
  });
}
